import { createClient } from '@supabase/supabase-js';
import fs from 'node:fs';
import { loadQaAccounts } from './lib/qaAccounts.mjs';
const env = Object.fromEntries(fs.readFileSync('.env.local','utf8').split(/\r?\n/).filter(l=>l.includes('=')).map(l=>{const i=l.indexOf('=');return [l.slice(0,i),l.slice(i+1).replace(/^"|"$/g,'')]}));
const sb = createClient(env.VITE_SUPABASE_URI, env.VITE_SUPABASE_ANON_KEY);
const a = loadQaAccounts({ requireBoth: false }).accounts[process.argv[2] || 'A'];
await sb.auth.signInWithPassword({ email: a.email, password: a.password });
const { data: u } = await sb.auth.getUser();
const { data: m } = await sb.from('company_members').select('company_id').eq('user_id', u.user.id).limit(1);
const cid = m[0].company_id;
const { data: co } = await sb.from('companies').select('enabled_modules,package_code').eq('id', cid).single();
console.log('modules:', JSON.stringify(co));
const s = await sb.from('suppliers').insert([{ company_id: cid, name: `QA-RLS ${Date.now()}` }]).select('id').single();
console.log('supplier insert', s.error?.message ?? 'ok');
const d = await sb.from('suppliers').delete().eq('id', s.data.id).select('id');
console.log('GERCEK RLS delete suppliers ->', JSON.stringify({ error: d.error?.message ?? null, rows: d.data, status: d.status }));
const r = await sb.rpc('soft_delete_supplier', { p_company_id: cid, p_supplier_id: s.data.id });
console.log('temizlik soft_delete', JSON.stringify(r.data), r.error?.message ?? '');
const cs = await sb.from('catalog_series').select('id', { count: 'exact', head: true }).eq('company_id', cid);
console.log('catalog_series select', cs.error?.message ?? `count=${cs.count}`);
