import { createClient } from '@supabase/supabase-js';
import fs from 'node:fs';
import { loadQaAccounts } from './lib/qaAccounts.mjs';
const env = Object.fromEntries(fs.readFileSync('.env.local','utf8').split(/\r?\n/).filter(l=>l.includes('=')).map(l=>{const i=l.indexOf('=');return [l.slice(0,i),l.slice(i+1).replace(/^"|"$/g,'')]}));
const sb = createClient(env.VITE_SUPABASE_URI, env.VITE_SUPABASE_ANON_KEY);
const a = loadQaAccounts({ requireBoth: false }).accounts.A;
await sb.auth.signInWithPassword({ email: a.email, password: a.password });
const { data: sups } = await sb.from('suppliers').select('id,name').like('name', 'QA-DEL%');
console.log('suppliers', JSON.stringify(sups));
const sid = sups[0].id;
const { data: tx } = await sb.from('supplier_transactions').select('id,transaction_type,amount').eq('supplier_id', sid);
console.log('tx', tx.length);
const r1 = await sb.from('supplier_transactions').delete().eq('id', tx[0].id).select('id');
console.log('delete one:', JSON.stringify(r1));
const { count } = await sb.from('supplier_transactions').select('id', { count: 'exact', head: true }).eq('supplier_id', sid);
console.log('remaining', count);
const d1 = await sb.from('supplier_transactions').delete().eq('supplier_id', sid).select('id');
const d2 = await sb.from('suppliers').delete().eq('id', sid).select('id');
console.log('cleanup tx', d1.data?.length, 'supplier', d2.data?.length, d1.error?.message || d2.error?.message || '');
