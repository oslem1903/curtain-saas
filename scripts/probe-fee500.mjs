import { chromium } from '@playwright/test';
import { loadQaAccounts } from './lib/qaAccounts.mjs';
const acc = loadQaAccounts({ requireBoth: false }).accounts.A;
const BASE = 'http://localhost:5199';
const b = await chromium.launch(); const ctx = await b.newContext({ viewport: { width: 1280, height: 900 } });
await ctx.addInitScript((id) => localStorage.setItem('curtain_saas_device_id', id), acc.deviceId);
const page = await ctx.newPage();
await page.goto(`${BASE}/#/login`);
await page.locator('input[type="email"]').first().fill(acc.email);
await page.locator('input[type="password"]').first().fill(acc.password);
await page.getByRole('button', { name: /^Giriş Yap$/ }).click();
await page.waitForURL(/#\/(dashboard|app\/dashboard|field)/, { timeout: 60000 });
const j = await page.evaluate(async () => { const sb = window.supabase; const { data } = await sb.from('installation_jobs').select('id,order_id,company_id').limit(1); return data?.[0]; });
const rpc = (fee) => page.evaluate(async ({ j, fee }) => { const { data, error } = await window.supabase.rpc('update_installer_job_fee', { p_company_id: j.company_id, p_job_id: j.id, p_price_type: 'manuel', p_unit_rate: 0, p_installer_fee: fee }); const { data: e } = await window.supabase.from('installer_earnings').select('id,total_earning,order_id').eq('order_id', j.order_id); return { error: error?.message, data, e }; }, { j, fee });
console.log('500:', JSON.stringify(await rpc(500)));
await page.goto(`${BASE}/#/orders/${j.order_id}`);
await page.waitForTimeout(6000);
const t = (await page.locator('body').innerText()).split(String.fromCharCode(160)).join(' ');
console.log(t.split(String.fromCharCode(10)).filter((l) => /Montaj maliyeti|Toplam maliyet|₺2\.0|₺500/i.test(l)).join(' | '));
console.log('350:', JSON.stringify(await rpc(350)));
await b.close();
